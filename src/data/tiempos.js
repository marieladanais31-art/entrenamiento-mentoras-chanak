export const horasModulo = (id) => ESTIMACIONES_MINUTOS[id]?.horas || 0
export function desgloseRealista(id, documentos = []) {
  const e = ESTIMACIONES_MINUTOS[id]
  if (!e) return null
  const pesos = documentos.map((d) => d.horas || 1)
  const totalPesos = pesos.reduce((s, n) => s + n, 0)
  return { ...Object.fromEntries(['video', 'lectura', 'practica', 'evidencia', 'kc'].map((k) => [k, e[k] / 60])), palabras: e.palabras, total: e.horas, documentos: documentos.map((d, i) => ({ ...d, horas: totalPesos ? e.documentos * pesos[i] / totalPesos / 60 : 0 })), criterio: 'Lectura de estudio estimada a 150 palabras/minuto, más 5 minutos de repaso. Documentos: consulta dirigida de apartados; práctica y evidencia por tarea. La práctica supervisada real se registra aparte según actividad, sin convertir semanas de calendario en horas.' }
}
